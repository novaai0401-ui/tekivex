#!/usr/bin/env node
// Walks every tutorial markdown file, counts words, and emits a TS module
// listing the paths considered "thin" for SEO and AdSense purposes.
//
// Run via `npm run prebuild` (and committed to the repo so vite + prerender
// pick up the same list). Re-run whenever you add or substantially edit a
// tutorial.

import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, dirname, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const CONTENT_DIR = join(ROOT, 'public', 'tutorials', 'content');
const OUT = join(ROOT, 'src', 'tutorials', 'thinTopics.ts');

export const THIN_WORD_THRESHOLD = 300;

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    const stat = statSync(full);
    if (stat.isDirectory()) out.push(...walk(full));
    else if (name.endsWith('.md')) out.push(full);
  }
  return out;
}

function countWords(md) {
  // Strip fenced code blocks and HTML before counting prose words.
  const stripped = md
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/`[^`]*`/g, ' ')
    .replace(/<[^>]+>/g, ' ');
  return (stripped.match(/\b[\w-]+\b/g) ?? []).length;
}

if (!existsSync(CONTENT_DIR)) {
  console.warn(`✗ ${CONTENT_DIR} not found — skipping thin-topic scan`);
  process.exit(0);
}

const files = walk(CONTENT_DIR);
const thin = [];
for (const file of files) {
  const md = readFileSync(file, 'utf8');
  const words = countWords(md);
  if (words < THIN_WORD_THRESHOLD) {
    const rel = relative(CONTENT_DIR, file).replace(/\\/g, '/').replace(/\.md$/, '');
    thin.push({ path: `/tutorials/${rel}`, words });
  }
}
thin.sort((a, b) => a.path.localeCompare(b.path));

const body = `// AUTO-GENERATED by scripts/compute-thin-topics.mjs — do not edit by hand.
// Regenerate after adding or substantially editing tutorials:
//   node scripts/compute-thin-topics.mjs

export const THIN_WORD_THRESHOLD = ${THIN_WORD_THRESHOLD};

/**
 * Tutorial pages with fewer than THIN_WORD_THRESHOLD words of prose
 * (code blocks stripped). These pages are:
 *   - marked <meta name="robots" content="noindex,follow">
 *   - excluded from sitemap.xml and feed.xml
 *   - rendered without an AdSlot (to avoid the AdSense "ads on
 *     low-value content" policy hit)
 */
export const THIN_TOPIC_PATHS: ReadonlySet<string> = new Set([
${thin.map((t) => `  '${t.path}', // ${t.words}w`).join('\n')}
]);

export function isThinTopic(path: string): boolean {
  return THIN_TOPIC_PATHS.has(path);
}
`;

writeFileSync(OUT, body, 'utf8');
console.log(
  `✓ ${thin.length} of ${files.length} tutorials are below ${THIN_WORD_THRESHOLD} words → ${relative(ROOT, OUT)}`,
);
